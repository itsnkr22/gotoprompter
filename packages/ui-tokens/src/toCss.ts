export type TokenGroup = Record<string, string>;
export type Tokens = Record<string, TokenGroup | string>;

/** Flattens `{color: {accent: '#..'}}` into `--vp-color-accent: #..;` declarations. */
export function toCssVars(tokens: Tokens, skip: readonly string[] = []): string[] {
  const lines: string[] = [];
  for (const [group, values] of Object.entries(tokens)) {
    if (group.startsWith('$') || skip.includes(group) || typeof values === 'string') continue;
    for (const [name, value] of Object.entries(values)) {
      lines.push(`  --vp-${group}-${name}: ${value};`);
    }
  }
  return lines;
}

/** Full stylesheet: dark defaults on :root, light overrides under [data-theme="light"]. */
export function buildStylesheet(tokens: Tokens): string {
  const light = tokens['color-light'];
  const lightLines =
    light && typeof light !== 'string'
      ? Object.entries(light).map(([name, value]) => `  --vp-color-${name}: ${value};`)
      : [];
  return [
    '/* Generated by @gotoprompter/ui-tokens. Do not edit. */',
    ':root {',
    ...toCssVars(tokens, ['color-light']),
    '}',
    '[data-theme="light"] {',
    ...lightLines,
    '}',
    '',
  ].join('\n');
}
