// One-off generator for placeholder marketing images (our own, brand-coloured; replaced by real
// screenshots and recordings later). Run: node scripts/make-placeholders.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import sharp from 'sharp';

const brand = JSON.parse(
  readFileSync(new URL('../../../packages/config/brand.json', import.meta.url), 'utf8'),
);
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');
const svg = (w, h, title, sub, accent = '#2DD4BF') => `
<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">
  <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#0b0b0d"/><stop offset="1" stop-color="#17201f"/></linearGradient></defs>
  <rect width="${w}" height="${h}" fill="url(#g)"/>
  <rect x="0" y="0" width="${w}" height="${Math.round(h * 0.012)}" fill="${accent}"/>
  <circle cx="${w - h * 0.25}" cy="${h * 0.3}" r="${h * 0.22}" fill="${accent}" opacity="0.12"/>
  <text x="${w * 0.06}" y="${h * 0.5}" font-family="Inter, Helvetica, Arial, sans-serif" font-size="${Math.round(h * 0.09)}" font-weight="700" fill="#ffffff">${esc(title)}</text>
  <text x="${w * 0.06}" y="${h * 0.62}" font-family="Inter, Helvetica, Arial, sans-serif" font-size="${Math.round(h * 0.045)}" fill="#A1A1AA">${esc(sub)}</text>
  <text x="${w * 0.06}" y="${h * 0.9}" font-family="Inter, Helvetica, Arial, sans-serif" font-size="${Math.round(h * 0.04)}" font-weight="600" fill="${accent}">${esc(brand.APP_NAME)}</text>
</svg>`;
const png = (file, w, h, t, s) =>
  sharp(Buffer.from(svg(w, h, t, s)))
    .png({ compressionLevel: 9 })
    .toFile(file);
const jpg = (file, w, h, t, s) =>
  sharp(Buffer.from(svg(w, h, t, s)))
    .jpeg({ quality: 70 })
    .toFile(file);

mkdirSync('public/images/blog', { recursive: true });
mkdirSync('public/videos/mac/posters', { recursive: true });
await png(
  'public/images/og-default.png',
  1200,
  630,
  'Read your script. Keep your eyes on the lens.',
  'A teleprompter that follows your voice',
);
await png(
  'public/images/mac-overlay-hero.png',
  1200,
  750,
  'Floating prompter window',
  'Placeholder screenshot of the Mac app',
);
await png(
  'public/images/web-app-hero.png',
  1200,
  750,
  'Web app prompter view',
  'Placeholder screenshot of the web app',
);

const blog = JSON.parse(readFileSync(new URL('./blog-images.json', import.meta.url), 'utf8'));
for (const [slug, title] of Object.entries(blog))
  await jpg(`public/images/blog/${slug}.jpg`, 1200, 630, title, 'Guide');

const features = JSON.parse(readFileSync('src/data/mac-features.json', 'utf8'));
for (const f of features) {
  const poster = `public/videos/mac/posters/${f.video}.jpg`;
  await jpg(poster, 640, 400, f.title, 'Placeholder until recorded');
  execFileSync('ffmpeg', [
    '-y',
    '-loglevel',
    'error',
    '-loop',
    '1',
    '-i',
    poster,
    '-t',
    '2',
    '-r',
    '10',
    '-vf',
    'scale=640:400',
    '-pix_fmt',
    'yuv420p',
    '-movflags',
    '+faststart',
    `public/videos/mac/${f.video}.mp4`,
  ]);
}
writeFileSync(
  'public/images/.placeholders',
  'Generated by scripts/make-placeholders.mjs. Replace with real screenshots and recordings.\n',
);
console.log('placeholders written');
